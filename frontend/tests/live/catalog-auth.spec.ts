import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

const fixture = JSON.parse(process.env.TF_FRONTEND_LIVE_FIXTURE!) as { marker: string; events: { id: string; name: string }[] }

test('real public catalogue, filters, sessions, prices and empty search', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('活动名称').fill(fixture.marker)
  await page.getByRole('button', { name: '搜索活动' }).click()
  await expect(page.locator('.event-card')).toHaveCount(3)
  await page.getByLabel('城市', { exact: true }).fill('上海')
  await page.getByRole('button', { name: '搜索活动' }).click()
  await expect(page.locator('.event-card')).toHaveCount(1)
  await page.getByRole('link', { name: new RegExp(fixture.marker) }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(fixture.events[0]!.name)
  await expect(page.getByRole('button', { name: /标准票/ })).toContainText('¥99.00')
  await expect(page.getByRole('button', { name: /优选票/ })).toContainText('¥199.00')
  await page.getByRole('button', { name: /标准票/ }).click()
  await expect(page.getByRole('complementary')).toContainText('¥99.00')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name: '返回活动列表' }).click()
  await page.getByLabel('活动名称').fill('missing_' + randomUUID())
  await page.getByRole('button', { name: '搜索活动' }).click()
  await expect(page.getByText('暂时没有找到活动')).toBeVisible()
})

test('real registration, duplicate rejection, failed login, selected-ticket return and refresh', async ({ page }) => {
  const username = 'web_' + randomUUID().replaceAll('-', '').slice(0, 18)
  const password = 'Test_' + randomUUID()
  await page.goto('/events/' + fixture.events[0]!.id)
  await page.getByRole('button', { name: /优选票/ }).click()
  await page.getByRole('link', { name: '登录并保留选择' }).click()
  await page.getByRole('link', { name: '立即注册' }).click()
  await expect(page.getByRole('heading', { name: '创建账号' })).toBeVisible()
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByLabel('确认密码').fill(password)
  await page.getByRole('button', { name: '注册账号' }).click()
  await expect(page.getByText('注册成功，请使用刚才的账号和密码登录。')).toBeVisible()
  await page.getByRole('link', { name: '立即注册' }).click()
  await expect(page.getByRole('heading', { name: '创建账号' })).toBeVisible()
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByLabel('确认密码').fill(password)
  await page.getByRole('button', { name: '注册账号' }).click()
  await expect(page.getByRole('alert')).toContainText('这个账号已被注册')
  await page.getByRole('link', { name: '去登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await page.getByLabel('密码', { exact: true }).fill('WrongPassword_123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('账号或密码不正确')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('.account-name')).toHaveText(username)
  await expect(page.getByRole('complementary')).toContainText('优选票')
  await expect(page.getByRole('complementary')).toContainText('¥199.00')
  await expect(page.getByRole('button', { name: '确认选票并下单' })).toBeEnabled()
  await page.reload()
  await expect(page.locator('.account-name')).toHaveText(username)
  await expect(page.getByRole('complementary')).toContainText('优选票')
  expect(await page.evaluate(() => JSON.stringify(Object.values(localStorage)))).not.toContain(password)
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('link', { name: '登录并保留选择' })).toBeVisible()
  await page.evaluate(() => sessionStorage.setItem('ticketflow.auth.v1', 'invalid.token.signature'))
  await page.reload()
  await expect(page.getByRole('status', { name: '登录状态' })).toContainText('登录已失效')
  expect(await page.evaluate(() => sessionStorage.getItem('ticketflow.auth.v1'))).toBeNull()
})
