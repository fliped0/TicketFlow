import { expect, test } from '@playwright/test'
import { mockApi } from './mock-api'

test('filter URL, pagination, empty results and retry after service failure', async ({ page }) => {
  const api = await mockApi(page)
  await page.goto('/')
  await expect(page.locator('.event-card')).toHaveCount(9)
  await page.getByRole('button', { name: 'Go to next page' }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.locator('.event-card')).toHaveCount(3)
  await page.getByLabel('城市', { exact: true }).fill('不存在')
  await page.getByRole('button', { name: '搜索活动' }).click()
  await expect(page.getByText('暂时没有找到活动')).toBeVisible()
  api.fail()
  await page.getByRole('button', { name: '清除筛选' }).click()
  await expect(page.getByRole('alert')).toContainText('服务暂时不可用')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.locator('.event-card')).toHaveCount(9)
})

test('registration, validation, bad password, selection return, persistence and logout', async ({ page }) => {
  await mockApi(page)
  await page.goto('/events/101')
  await expect(page.locator('.description')).toContainText('<img src=x')
  expect(await page.evaluate(() => 'injected' in window)).toBe(false)
  await expect(page.getByRole('button', { name: /售罄票/ })).toBeDisabled()
  await page.getByRole('button', { name: /标准票/ }).click()
  await expect(page.getByRole('complementary')).toContainText('¥99.00')
  await page.getByRole('link', { name: '登录并保留选择' }).click()
  await page.getByRole('link', { name: '立即注册' }).click()
  await page.getByLabel('账号', { exact: true }).fill('demo_user')
  await page.getByLabel('密码', { exact: true }).fill('short')
  await page.getByRole('button', { name: '注册账号' }).click()
  await expect(page.getByRole('alert')).toContainText('8–64')
  await page.getByLabel('密码', { exact: true }).fill('TestPassword_123')
  await page.getByLabel('确认密码').fill('TestPassword_123')
  await page.getByRole('button', { name: '注册账号' }).click()
  await expect(page.getByText('注册成功，请使用刚才的账号和密码登录。')).toBeVisible()
  await page.getByLabel('密码', { exact: true }).fill('WrongPassword_123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('账号或密码不正确')
  await page.getByLabel('密码', { exact: true }).fill('TestPassword_123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/events\/101\?.*tier=21/)
  await expect(page.locator('.account-name')).toHaveText('demo_user')
  await expect(page.getByRole('complementary')).toContainText('标准票')
  await page.reload()
  await expect(page.locator('.account-name')).toHaveText('demo_user')
  await expect(page.getByRole('complementary')).toContainText('¥99.00')
  expect(await page.evaluate(() => JSON.stringify(Object.values(localStorage)))).not.toContain('TestPassword')
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('link', { name: '登录并保留选择' })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('ticketflow.auth.v1'))).toBeNull()
})

test('rapid session switching discards stale tiers and expired identity clears the account', async ({ page }) => {
  const api = await mockApi(page)
  await page.goto('/events/101')
  await expect(page.getByRole('button', { name: /标准票/ })).toBeVisible()
  api.delay()
  const sessions = page.locator('.session-grid button')
  await sessions.nth(0).click()
  await sessions.nth(1).click()
  await expect(page.getByRole('button', { name: /第二场票/ })).toBeVisible()
  await page.waitForTimeout(450)
  await expect(page.getByRole('button', { name: /标准票/ })).toHaveCount(0)
  await page.evaluate(() => sessionStorage.setItem('ticketflow.auth.v1', 'expired.token'))
  await page.reload()
  await expect(page.getByRole('status', { name: '登录状态' })).toContainText('登录已失效')
  expect(await page.evaluate(() => sessionStorage.getItem('ticketflow.auth.v1'))).toBeNull()
})
