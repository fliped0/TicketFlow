for (const operation of ['CANCEL', 'REFUND'] as const) {
  test(`lost ${operation} receipt survives refresh with the original key and frozen amount`, async ({ page }) => {
    const api = await mockApi(page); await login(page); await purchase(page)
    if (operation === 'REFUND') { await payment(page); api.loseRefund() } else api.loseCancel()
    await page.getByRole('button', { name: operation === 'REFUND' ? '申请模拟退款' : '取消订单', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: operation === 'REFUND' ? '确认模拟退款' : '确认取消订单' })
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: operation === 'REFUND' ? '确认模拟退款' : '确认取消订单' }).click()
    await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('有一笔操作结果待确认')
    const first = api.attempts.find(item => item.operation === operation)!
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    await page.reload(); await page.getByRole('button', { name: '恢复原操作结果' }).click()
    await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('操作已完成')
    const attempts = api.attempts.filter(item => item.operation === operation)
    expect(attempts).toHaveLength(2); expect(attempts[1]!.key).toBe(first.key); expect(attempts[1]!.body).toEqual({})
    await expect(page.locator('.order-detail-card .order-status')).toHaveText(operation === 'REFUND' ? '已退款' : '已取消')
    if (operation === 'REFUND') await expect(page.getByRole('region', { name: '模拟退款记录' })).toContainText('800')
  })
}

