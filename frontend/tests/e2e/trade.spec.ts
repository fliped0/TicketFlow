import { expect, test, type Page } from '@playwright/test'
import { mockApi } from './mock-api'
async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill('demo_user')
  await page.getByLabel('密码', { exact: true }).fill('TestPassword_123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('.account-name')).toBeVisible()
}
async function choose(page: Page) {
  await page.goto('/events/101')
  await page.getByRole('button', { name: /标准票/ }).click()
  await page.getByRole('button', { name: '确认选票并下单' }).click()
  const dialog = page.getByRole('dialog', { name: '确认下单' })
  await dialog.getByRole('checkbox').check()
  return dialog
}
test('explicit confirmation, duplicate click protection, payment and status-filtered orders', async ({ page }) => {
  const api = await mockApi(page); await login(page)
  await page.goto('/events/101'); await page.getByRole('button', { name: /标准票/ }).click()
  await page.getByRole('button', { name: '确认选票并下单' }).click()
  const dialog = page.getByRole('dialog', { name: '确认下单' })
  await expect(dialog.getByRole('button', { name: '确认提交订单' })).toBeDisabled()
  expect(api.attempts).toHaveLength(0)
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认提交订单' }).evaluate(el => { (el as HTMLButtonElement).click(); (el as HTMLButtonElement).click() })
  await expect(page).toHaveURL(/orders\/500$/)
  expect(api.attempts.filter(item => item.operation === 'CREATE')).toHaveLength(1)
  await expect(page.locator('.order-detail-card .order-status')).toHaveText('待支付')
  await expect(page.getByLabel('支付剩余时间')).toBeVisible()
  await page.getByRole('button', { name: '模拟支付', exact: true }).click()
  const payment = page.getByRole('dialog', { name: '确认模拟支付' })
  await expect(payment.getByRole('button', { name: '确认模拟支付' })).toBeDisabled()
  await payment.getByRole('checkbox').check()
  await payment.getByRole('button', { name: '确认模拟支付' }).click()
  await expect(page.locator('.order-detail-card .order-status')).toHaveText('已支付')
  await expect(page.getByRole('region', { name: '模拟支付记录' })).toContainText('700')
  await page.getByRole('link', { name: '返回我的订单' }).click()
  await page.getByLabel('订单状态').selectOption('PAID')
  await expect(page.locator('.order-card')).toHaveCount(1)
  await expect(page.locator('.order-card .order-status')).toHaveText('已支付')
})
test('lost create receipt survives refresh and restores the original key and tier despite changed selection', async ({ page }) => {
  const api = await mockApi(page); await login(page); api.loseCreate()
  const dialog = await choose(page)
  await dialog.getByRole('button', { name: '确认提交订单' }).click()
  await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('有一笔操作结果待确认')
  const first = api.attempts[0]!
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.reload()
  await page.locator('.session-grid button').nth(1).click()
  await page.getByRole('button', { name: /第二场票/ }).click()
  await expect(page.getByRole('button', { name: '确认选票并下单' })).toBeDisabled()
  await page.getByRole('button', { name: '恢复原操作结果' }).click()
  await expect(page).toHaveURL(/orders\/500$/)
  expect(api.attempts[1]!.key).toBe(first.key)
  expect(api.attempts[1]!.body).toEqual(first.body)
  expect(api.orders).toHaveLength(1)
  await expect(page.locator('.order-detail-card')).toContainText('¥99.00')
})
test('lost payment receipt restores the same payment, rather than issuing a new operation', async ({ page }) => {
  const api = await mockApi(page); await login(page)
  const dialog = await choose(page); await dialog.getByRole('button', { name: '确认提交订单' }).click()
  await expect(page).toHaveURL(/orders\/500$/)
  api.losePay()
  await page.getByRole('button', { name: '模拟支付', exact: true }).click()
  const payment = page.getByRole('dialog', { name: '确认模拟支付' })
  await payment.getByRole('checkbox').check(); await payment.getByRole('button', { name: '确认模拟支付' }).click()
  await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('有一笔操作结果待确认')
  const original = api.attempts.find(item => item.operation === 'PAY')!
  await payment.getByRole('button', { name: '关闭', exact: true }).click()
  await page.reload(); await page.getByRole('button', { name: '恢复原操作结果' }).click()
  await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('操作已完成')
  const payments = api.attempts.filter(item => item.operation === 'PAY')
  expect(payments).toHaveLength(2); expect(payments[1]!.key).toBe(original.key)
  await expect(page.getByRole('region', { name: '模拟支付记录' })).toContainText('700')
})
