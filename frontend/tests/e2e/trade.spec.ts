test('another tab cannot recover or replace an operation while its original POST is in progress', async ({ page, context }) => {
  const firstApi = await mockApi(page); await login(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/v1/orders', async route => {
    if (route.request().method() === 'POST') await gate
    await route.fallback()
  })
  const other = await context.newPage()
  const otherApi = await mockApi(other)
  await other.addInitScript(() => sessionStorage.setItem('ticketflow.auth.v1', 'mock.token.value'))
  try {
    const dialog = await choose(page); await dialog.getByRole('button', { name: '确认提交订单' }).click()
    await expect(page.getByRole('region', { name: '交易结果与恢复' })).toContainText('正在处理已确认的操作')
    const key = await page.evaluate(() => JSON.parse(localStorage.getItem('ticketflow.trade.v1.1')!).key)
    await other.goto('/events/101'); await other.getByRole('button', { name: /标准票/ }).click()
    await expect(other.getByRole('button', { name: '确认选票并下单' })).toBeDisabled()
    await other.getByRole('button', { name: '恢复原操作结果' }).click()
    await expect(other.getByRole('region', { name: '交易结果与恢复' }).getByRole('alert')).toContainText('其他标签页正在处理')
    expect(otherApi.attempts).toHaveLength(0)
    expect(await other.evaluate(() => JSON.parse(localStorage.getItem('ticketflow.trade.v1.1')!).key)).toBe(key)
    release()
    await expect(page).toHaveURL(/orders\/500$/)
    expect(firstApi.attempts).toHaveLength(1); expect(firstApi.attempts[0]!.key).toBe(key)
  } finally { release(); await other.close() }
})
